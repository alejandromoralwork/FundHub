/**
 * FILE: apps/admin/src/app/(console)/reports/page.tsx
 * PART: console (apps/admin)
 * WHAT IT DOES: The "Reports" page. It lists the PDF reports staff have uploaded (newest first) and the two
 *   built-in reports the website generates itself from live data, with links to view them on the website.
 * WHERE IT RUNS: on the server (Node.js), as a server component reading the database; ReportsView runs in
 *   the browser.
 * FRAMEWORK NOTES: page.tsx in app/(console)/reports = the URL /admin/reports ("(console)" is a route group).
 * TYPESCRIPT YOU WILL SEE HERE: arrays of objects, `as` type assertions, `async`/`await`.
 */

// `import { a } from "b"` loads named exports from module "b".
// Type for the page metadata (browser-tab title).
import type { Metadata } from "next";
// Drizzle ORM helper: `desc` = sort descending.
import { desc } from "drizzle-orm";
// `@fundhub/…` = our shared packages. Database connection and the reports table.
import { db } from "@fundhub/db/client";
import { reports } from "@fundhub/db/schema";
// `@/…` = this app's src folder. The screen and the type of one uploaded-report row.
import { ReportsView, type ReportRow } from "@/components/ops-views";
// Role table and login/role check.
import { CAN, requireStaff } from "@/lib/auth";
// The public website's address, for "view" links.
import { websiteUrl } from "@/lib/site";

/** Kind: constant. Browser-tab title, read by Next.js. */
export const metadata: Metadata = { title: "Reports" };

/**
 * Kind: constant (an array of objects — a list where each item has slug, title and visibility).
 * Built-in reports are generated by the website from live data (apps/web/src/content/reports.ts).
 * "public" = anyone can read it; "private" = only for logged-in/paying users.
 */
const BUILT_IN = [
  { slug: "market-snapshot", title: "Luxembourg Fund Services Market Snapshot", visibility: "public" },
  { slug: "provider-intelligence", title: "Provider Intelligence Report", visibility: "private" },
];

/**
 * Kind: React component (async server component) — the page.
 * Parameters: none.
 * @returns `Promise<JSX>`: the reports screen markup.
 */
export default async function ReportsPage() {
  // Only roles in CAN.editData (owner, operations).
  await requireStaff(CAN.editData);
  // Uploaded reports, newest first. The PDF file itself is not selected (it is large); only its size.
  const rows = await db
    .select({ id: reports.id, slug: reports.slug, title: reports.title, period: reports.period, summary: reports.summary, visibility: reports.visibility, fileSize: reports.fileSize, createdAt: reports.createdAt })
    .from(reports)
    .orderBy(desc(reports.createdAt));
  // JSON round-trip for the browser (Dates -> strings); `as ReportRow[]` labels the type.
  return <ReportsView uploaded={JSON.parse(JSON.stringify(rows)) as ReportRow[]} builtIn={BUILT_IN} websiteUrl={websiteUrl()} />;
}
