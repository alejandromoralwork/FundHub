#!/usr/bin/env bash
# FILE: infra/vm/bin/metabase-install.sh
# WHAT IT DOES: Installs FundHub Data Intelligence = Metabase (open source) on this VM, served at https://<domain>/bi.
#   - Java 21 runtime + a pinned metabase.jar (SHA-256 checked) in /opt/metabase, run by systemd as user `metabase`
#     (unit infra/vm/systemd/fundhub-metabase.service, listens on 127.0.0.1:3010 only; Caddy publishes it).
#   - Metabase's own data (users, questions, dashboards) in PostgreSQL database `metabase`, so the nightly backup
#     covers it (not the default H2 file).
#   - Read-only login `fundhub_bi_ro` on the Intelligence DB: SELECT only, read-only transactions, 30 s statement
#     timeout, 5 connections. Metabase reads the pipeline through it over localhost; nothing new is exposed.
#   Secrets are generated once and never printed: /etc/metabase/metabase.env (mode 600) and
#   ~/.fundhub-secrets/bi-ro-db-url (the read-only connection string, used by `npm run bi:provision`).
# USAGE: sudo bash infra/vm/bin/metabase-install.sh            install / update to the pinned version (idempotent)
#        sudo bash infra/vm/bin/metabase-install.sh --grants   re-apply fundhub_bi_ro privileges only
# NEEDS: about 1.5 GB of free memory (VM resized to 8 GB). Upgrading Metabase = change MB_VERSION + MB_SHA256 below.
set -euo pipefail

MB_VERSION=v0.65.3
MB_SHA256=5230dea520f341bf60250f59e882e2cf69c958f7bed42eec05cb4b7c61cf6bf5   # sha256 of downloads.metabase.com/$MB_VERSION/metabase.jar
MB_DIR=/opt/metabase
MB_ENV=/etc/metabase/metabase.env
MB_PORT=3010
ENGINE_DB=fundhub_engine
ENGINE_OWNER=fundhub_engine
BI_ROLE=fundhub_bi_ro
SCHEMAS=(raw staging clean match core ops mart)
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
DOMAIN=${DOMAIN:-$(awk 'NF && $1 !~ /^#/ && /\{/ {print $1; exit}' /etc/caddy/Caddyfile)}
APP_USER=${APP_USER:-${SUDO_USER:-$(stat -c %U "$REPO")}}
SECRETS_DIR=$(getent passwd "$APP_USER" | cut -d: -f6)/.fundhub-secrets

[ "$(id -u)" = 0 ] || { echo "Run with sudo." >&2; exit 1; }
say() { printf '\n== %s\n' "$*"; }
pw() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 40; }
psql_su() { sudo -u postgres psql -v ON_ERROR_STOP=1 -qAt "$@"; }
role_exists() { [ -n "$(psql_su -c "select 1 from pg_roles where rolname = '$1'")" ]; }

grants() {
  local g="GRANT CONNECT ON DATABASE $ENGINE_DB TO $BI_ROLE;"
  for s in "${SCHEMAS[@]}"; do
    g+="
GRANT USAGE ON SCHEMA $s TO $BI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA $s TO $BI_ROLE;
ALTER DEFAULT PRIVILEGES FOR ROLE $ENGINE_OWNER IN SCHEMA $s GRANT SELECT ON TABLES TO $BI_ROLE;"
  done
  psql_su -d "$ENGINE_DB" -c "$g"
}
[ "${1:-}" = "--grants" ] && { grants; echo "Privileges of $BI_ROLE re-applied."; exit 0; }

say "Java runtime"
command -v java >/dev/null || apt-get install -y -q openjdk-21-jre-headless >/dev/null
java -version 2>&1 | head -1

say "Metabase $MB_VERSION"
id metabase >/dev/null 2>&1 || useradd --system --home "$MB_DIR" --shell /usr/sbin/nologin metabase
install -d -o metabase -g metabase -m 750 "$MB_DIR" "$MB_DIR/plugins"
if ! echo "$MB_SHA256  $MB_DIR/metabase.jar" | sha256sum -c - >/dev/null 2>&1; then
  tmp="$(mktemp)"
  curl -fsSL -o "$tmp" "https://downloads.metabase.com/$MB_VERSION/metabase.jar"
  echo "$MB_SHA256  $tmp" | sha256sum -c - >/dev/null || { echo "metabase.jar checksum mismatch, not installed." >&2; rm -f "$tmp"; exit 1; }
  install -o metabase -g metabase -m 640 "$tmp" "$MB_DIR/metabase.jar"; rm -f "$tmp"
  echo "installed $MB_DIR/metabase.jar"
fi

say "Metabase application database"
install -d -m 750 -o root -g metabase /etc/metabase
if ! role_exists metabase; then
  MB_PW=$(pw)
  psql_su -c "CREATE ROLE metabase LOGIN PASSWORD '$MB_PW' CONNECTION LIMIT 20"
  psql_su -c "CREATE DATABASE metabase OWNER metabase ENCODING 'UTF8' TEMPLATE template0"
  umask 077
  cat >"$MB_ENV" <<EOF
# Metabase (FundHub Data Intelligence). Generated by infra/vm/bin/metabase-install.sh. Never commit or print.
MB_DB_TYPE=postgres
MB_DB_HOST=127.0.0.1
MB_DB_PORT=5432
MB_DB_DBNAME=metabase
MB_DB_USER=metabase
MB_DB_PASS=$MB_PW
# Encrypts the data-source passwords Metabase stores. Must never change once set.
MB_ENCRYPTION_SECRET_KEY=$(pw)
EOF
  unset MB_PW
fi
# Non-secret settings: rewritten on every run so they follow this script.
sed -i '/^MB_SITE_URL=\|^MB_JETTY_HOST=\|^MB_JETTY_PORT=\|^MB_ANON_TRACKING_ENABLED=\|^MB_CHECK_FOR_UPDATES=\|^MB_PLUGINS_DIR=\|^MB_EMOJI_IN_LOGS=\|^MB_COLORIZE_LOGS=/d' "$MB_ENV"
cat >>"$MB_ENV" <<EOF
MB_SITE_URL=https://$DOMAIN/bi
MB_JETTY_HOST=127.0.0.1
MB_JETTY_PORT=$MB_PORT
MB_PLUGINS_DIR=$MB_DIR/plugins
MB_ANON_TRACKING_ENABLED=false
MB_CHECK_FOR_UPDATES=false
MB_EMOJI_IN_LOGS=false
MB_COLORIZE_LOGS=false
EOF
chown root:metabase "$MB_ENV"; chmod 640 "$MB_ENV"

say "Read-only login $BI_ROLE on $ENGINE_DB"
URL_FILE=$SECRETS_DIR/bi-ro-db-url
if ! role_exists "$BI_ROLE" || [ ! -s "$URL_FILE" ]; then
  BI_PW=$(pw)
  role_exists "$BI_ROLE" && verb=ALTER || verb=CREATE
  psql_su -c "$verb ROLE $BI_ROLE LOGIN PASSWORD '$BI_PW' CONNECTION LIMIT 5 NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT"
  install -d -o "$APP_USER" -g "$APP_USER" -m 700 "$SECRETS_DIR"
  umask 077
  echo "postgres://$BI_ROLE:$BI_PW@127.0.0.1:5432/$ENGINE_DB" >"$URL_FILE"
  chown "$APP_USER:$APP_USER" "$URL_FILE"; chmod 600 "$URL_FILE"
  unset BI_PW
  echo "connection string written to $URL_FILE"
fi
# Defence in depth: even a query that slipped past the grants cannot write, and runaway reports are stopped.
psql_su -c "ALTER ROLE $BI_ROLE SET default_transaction_read_only = on"
psql_su -c "ALTER ROLE $BI_ROLE SET statement_timeout = '30s'"
psql_su -c "ALTER ROLE $BI_ROLE SET idle_in_transaction_session_timeout = '60s'"
grants

say "Service"
install -m 644 "$REPO/infra/vm/systemd/fundhub-metabase.service" /etc/systemd/system/fundhub-metabase.service
systemctl daemon-reload
systemctl enable fundhub-metabase >/dev/null 2>&1
systemctl restart fundhub-metabase
printf 'waiting for Metabase (first start takes 1–3 minutes)'
for _ in $(seq 1 90); do
  curl -fsS -m 3 "http://127.0.0.1:$MB_PORT/api/health" 2>/dev/null | grep -q ok && { echo " ready"; break; }
  printf .; sleep 4
done
curl -fsS -m 3 "http://127.0.0.1:$MB_PORT/api/health" 2>/dev/null | grep -q ok || echo " not ready yet: journalctl -u fundhub-metabase -f"

echo
echo "Done. Metabase runs at https://$DOMAIN/bi (Authelia 2FA, then Metabase login)."
echo "First time only — see docs/data-intelligence.md §Setup:"
echo "  1) open https://$DOMAIN/bi, create the admin account (skip 'add your data');"
echo "  2) Admin → Embedding → enable Static embedding, copy the secret key → Vercel METABASE_EMBED_SECRET;"
echo "  3) Admin → Settings → Authentication → API keys → create one (group Administrators) → METABASE_API_KEY;"
echo "  4) npm run bi:provision (registers both databases, creates the system reports)."
